@dataclass(frozen=True)
class EpistemicReport:
    """
    The final output of VIGÍA is not a verdict.
    It is a structured epistemic report with full traceability.

    `evaluated_at` is required and injected by the caller. It carried a
    `default_factory=datetime.utcnow` before integration, which reads the
    wall clock at construction time: two runs over identical evidence would
    produce two different reports, and no third party could reproduce either.
    Removing implicit clock reads from the ontology was one of the deliberate
    choices of this revision; the report layer had kept one.
    """
    report_id: str
    engine_version: str
    ruleset_version: str
    kernel_snapshot: KernelSnapshot
    assessment_matrix: AssessmentMatrix
    matched_patterns: Tuple[AbductivePattern, ...]
    evaluated_at: datetime
    abstention_reason: Optional[str] = None
    causal_coherence_note: str = ""
