# PART VI: ASSESSMENT MATRIX (Structured epistemic report, not a verdict)
# =============================================================================

@dataclass(frozen=True)
class AssessmentCell:
    """One cell in the assessment matrix. One claim, one observation, one relation."""
    layer: AuthorityLayer
    claim_id: str
    observation_id: str
    verdict: AbductiveVerdict
    hypothesis: Optional[Hypothesis]
    status: ClaimStatus
    temporal_coverage: TemporalCoverage


@dataclass(frozen=True)
class AssessmentMatrix:
    """
    The Tribunal does not emit PASS/FAIL.
    It emits a matrix of abductive assessments per claim/observation pair.
    """
    cells: Tuple[AssessmentCell, ...]
    evaluated_at: datetime
    kernel_snapshot: Optional[KernelSnapshot] = None

    def by_layer(self, layer: AuthorityLayer) -> Tuple[AssessmentCell, ...]:
        return tuple(c for c in self.cells if c.layer == layer)

    def by_claim(self, claim_id: str) -> Tuple[AssessmentCell, ...]:
        return tuple(c for c in self.cells if c.claim_id == claim_id)

    def hypotheses(self) -> Tuple[Hypothesis, ...]:
        seen: Set[str] = set()
        hypos: List[Hypothesis] = []
        for c in self.cells:
            if c.hypothesis and c.hypothesis.hypo_id not in seen:
                seen.add(c.hypothesis.hypo_id)
                hypos.append(c.hypothesis)
        return tuple(hypos)


