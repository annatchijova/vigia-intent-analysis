# ---------------------------------------------------------------------------
# Architecture and original implementation:
#     Kimi (Moonshot AI) — VIGIA AI Collective.
#     Kimi's central correction was removing a single "EpistemicStatus" that
#     silently mixed two dimensions, and splitting it into HypothesisMode
#     (what kind of explanation this is) and EvaluationState (where it sits in
#     the engine's lifecycle). AbductivePattern was introduced as a layer
#     between raw observation and generated hypothesis so that rules recognize
#     patterns instead of degenerating into stimulus-response reflexes.
#
#     The constraint the whole file exists to enforce:
#         An observation does not destroy a claim. It modifies the abductive
#         space.
#     That is the Peircean reading: a sign does not kill its object nor
#     replace the theory; it generates a possible inference which must then
#     enter a process of evaluation.
#
# Design review of the previous revision:
#     ChatGPT (OpenAI) — VIGIA AI Collective.
#     Graded the prior revision 8.5/10 and located the residual gaps: free
#     text still sitting where types belong, and Hypothesis.statement carrying
#     the causal content as prose rather than structure.
#
# Integration, defect repair and determinism hardening:
#     Claude (Anthropic). See docs/EPISTEMIC_KERNEL.md.
#
# Separations that must survive any refactor of this file:
#     authority != evidence
#     observation != interpretation
#     interpretation != hypothesis
#     hypothesis != verdict
#     operational state != epistemic force
#     origin of a claim != justification of a claim
