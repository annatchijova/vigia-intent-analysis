# PART V: ABDUCTIVE TRIBUNAL (Generates hypotheses. Never judges.)
# =============================================================================

@dataclass(frozen=True)
class TribunalRule:
    """
    A rule in the Tribunal.
    Maps observations to abductive effects on claims.
    Primary output is always hypothesis generation or compatibility assessment.
    """
    # Target filters (None = wildcard)
    target_domain: Optional[Domain] = None
    target_layer: Optional[AuthorityLayer] = None
    target_role: Optional[ClaimRole] = None

    # Observation trigger
    obs_kind: Optional[ObservationKind] = None
    obs_domain: Optional[Domain] = None

    # Abductive effect
    verdict: AbductiveVerdict = AbductiveVerdict.ABSTAIN
    generates_hypothesis: Optional[str] = None
    required_context: Tuple[str, ...] = field(default_factory=tuple)
    hypothesis_mode: HypothesisMode = HypothesisMode.EXPLANATORY


class AbductiveTribunal:
    """
    The Tribunal. Does not contradict claims directly.
    Observations modify the abductive space. Claims are questioned, not refuted.
    """

    def __init__(self):
        self._rules: List[TribunalRule] = []
        self._patterns: List[AbductivePattern] = []

    def add_rule(self, rule: TribunalRule) -> None:
        self._rules.append(rule)

    def add_pattern(self, pattern: AbductivePattern) -> None:
        self._patterns.append(pattern)

    def _match_rules(
        self,
        observation: Observation,
        claim: OntologyClaim
    ) -> List[TribunalRule]:
        """Collect all matching rules. Deterministic (registration order)."""
        matches: List[TribunalRule] = []
        for rule in self._rules:
            if rule.target_domain is not None and claim.domain != rule.target_domain:
                continue
            if rule.target_layer is not None and claim.layer != rule.target_layer:
                continue
            if rule.target_role is not None and claim.claim_role != rule.target_role:
                continue
            if rule.obs_kind is not None and observation.kind != rule.obs_kind:
                continue
            if rule.obs_domain is not None and observation.domain != rule.obs_domain:
                continue
            matches.append(rule)
        return matches

    def _generate_hypothesis(
        self,
        rule: TribunalRule,
        observation: Observation,
        claim: OntologyClaim
    ) -> Optional[Hypothesis]:
        """Generate a hypothesis from a matched rule. Never judge."""
        if rule.verdict != AbductiveVerdict.GENERATES_HYPOTHESIS:
            return None
        if not rule.generates_hypothesis:
            return None
        return Hypothesis(
            hypo_id=f"hypo.{observation.obs_id}.{claim.claim_id}",
            statement=rule.generates_hypothesis,
            hypothesis_mode=rule.hypothesis_mode,
            evaluation_state=EvaluationState.GENERATED,
            supporting_observations=(observation.obs_id,),
            supporting_claims=(claim.claim_id,),
            required_context_keys=tuple(rule.required_context),
            generated_by_pattern=None,
        )

    def evaluate(
        self,
        observation: Observation,
        claim: OntologyClaim
    ) -> Tuple[AbductiveVerdict, Optional[Hypothesis]]:
        """
        Deterministic. Collects ALL matching rules.
        If all agree: returns that verdict.
        If they disagree: returns ABSTAIN.
        If none match: returns ABSTAIN.
        Primary output is always GENERATES_HYPOTHESIS or COMPATIBLE.
        Never CONFLICT_DETECTED as primary.

        Agreement is checked on the verdict AND on the hypothesis the rules
        would generate. Two rules that both say GENERATES_HYPOTHESIS but
        propose different explanations do not agree in any sense that matters:
        emitting only the first-registered one would silently discard a rival
        abduction, which is precisely the collapse this engine exists to
        prevent. Disagreement at that level abstains, same as verdict-level
        disagreement.
        """
        matches = self._match_rules(observation, claim)

        if not matches:
            return (AbductiveVerdict.ABSTAIN, None)

        verdicts = set(r.verdict for r in matches)
        if len(verdicts) > 1:
            return (AbductiveVerdict.ABSTAIN, None)

        proposals = set(
            (r.generates_hypothesis, r.hypothesis_mode, tuple(r.required_context))
            for r in matches
        )
        if len(proposals) > 1:
            return (AbductiveVerdict.ABSTAIN, None)

        rule = matches[0]
        hypo = self._generate_hypothesis(rule, observation, claim)

        return (rule.verdict, hypo)

    def evaluate_all(
        self,
        observation: Observation,
        registry: OntologyRegistry
    ) -> Dict[str, Tuple[AbductiveVerdict, Optional[Hypothesis]]]:
        """
        Evaluate an observation against all active claims in a domain.

        Insertion order follows registry.by_domain(), which is sorted by
        claim_id, so the returned mapping serializes identically across runs.
        """
        results: Dict[str, Tuple[AbductiveVerdict, Optional[Hypothesis]]] = {}
        for claim in registry.by_domain(observation.domain):
            if registry.status(claim.claim_id) == ClaimStatus.ACTIVE:
                results[claim.claim_id] = self.evaluate(observation, claim)
        return results

    def match_patterns(
        self,
        observation: Observation
    ) -> List[AbductivePattern]:
        """Match observation against known abductive patterns. Deterministic."""
        matched: List[AbductivePattern] = []
        for pattern in self._patterns:
            if observation.kind != pattern.observation_kind:
                continue
            if (pattern.affected_domain is not None
                    and observation.domain != pattern.affected_domain):
                continue
            # Check required context keys exist in observation
            obs_ctx = observation.context_dict()
            if all(k in obs_ctx for k in pattern.required_context_keys):
                matched.append(pattern)
        return matched


