    causal_template: str
    affected_domain: Optional[Domain] = None
    affected_role: Optional[ClaimRole] = None
    required_context_keys: Tuple[str, ...] = field(default_factory=tuple)
    hypothesis_mode: HypothesisMode = HypothesisMode.EXPLANATORY


