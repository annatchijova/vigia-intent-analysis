@dataclass(frozen=True)
class Hypothesis:
    """
    Output of the Tribunal. Not a verdict. An abductive candidate.
    Epistemic status separated into mode (what kind) and state (where in
    lifecycle).

    `required_context_keys` carries the names of the context a rule declared
    necessary. The pre-integration revision built this as a tuple of empty
    ClaimContext objects, one per declared key — preserving the count and
    discarding every name, so a hypothesis could report "I need two things"
    without being able to say which two. The keys are the audit-relevant part.

    `statement` remains prose. The ChatGPT review is right that an auditable
    machine will eventually need a causal structure (cause / condition /
    effect nodes) with the prose derived from it rather than primary. That is
    a design decision for the maintainer, not a repair to make in passing; it
    is recorded as an open question in docs/EPISTEMIC_KERNEL.md.
    """
    hypo_id: str
    statement: str
    hypothesis_mode: HypothesisMode
    evaluation_state: EvaluationState
    supporting_observations: Tuple[str, ...]
    supporting_claims: Tuple[str, ...]
    required_context_keys: Tuple[str, ...] = field(default_factory=tuple)
    generated_by_pattern: Optional[str] = None


