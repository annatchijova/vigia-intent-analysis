# PART II: CLAIM GRAPH (Intermediate semantic layer — computational nodes)
# =============================================================================

@dataclass(frozen=True)
class ClaimNode:
    """
    Computational node in the abductive graph.
    Semiotic relation (Peirce) is separate from node type.
    """
    node_id: str
    node_type: NodeType
    sign_relation: Optional[SignRelation] = None
    context: ClaimContext = field(default_factory=ClaimContext)
    status_at_evaluation: ClaimStatus = ClaimStatus.ACTIVE
    temporal_coverage: TemporalCoverage = TemporalCoverage.UNKNOWN


class ClaimGraph:
    """
    Directed graph of claim dependencies and semantic relationships.
    Not the abductive complex yet. The scaffold for it.

    Edge direction: `add_dependency(from_id, to_id)` means "from_id depends on
    to_id". Therefore `dependencies(from_id)` contains to_id, and
    `dependents(to_id)` contains from_id — the same direction the registry's
    reverse graph uses. The two accessors were transposed relative to that
    reading before integration, so a caller asking for dependents received
    dependencies and the cascade would have walked the graph backwards.
    """

    def __init__(self):
        self._nodes: Dict[str, ClaimNode] = {}
        self._edges: Dict[str, Set[str]] = {}     # node -> what it depends on
        self._reverse: Dict[str, Set[str]] = {}   # node -> what depends on it

    def add_node(self, node: ClaimNode) -> None:
        self._nodes[node.node_id] = node
        self._edges.setdefault(node.node_id, set())
        self._reverse.setdefault(node.node_id, set())

    def add_dependency(self, from_id: str, to_id: str) -> None:
        """Record that `from_id` depends on `to_id`."""
        self._edges.setdefault(from_id, set()).add(to_id)
        self._reverse.setdefault(to_id, set()).add(from_id)

    def node(self, node_id: str) -> Optional[ClaimNode]:
        return self._nodes.get(node_id)

    def node_ids(self) -> Tuple[str, ...]:
        return tuple(sorted(self._nodes))

    def dependencies(self, node_id: str) -> Tuple[str, ...]:
        """What this node depends on. Sorted — iteration order is contractual."""
        return tuple(sorted(self._edges.get(node_id, set())))

    def dependents(self, node_id: str) -> Tuple[str, ...]:
        """What depends on this node. Sorted — iteration order is contractual."""
        return tuple(sorted(self._reverse.get(node_id, set())))

    def subgraph(self, root_ids: FrozenSet[str]) -> "ClaimGraph":
        """
        Deterministic extraction of the transitive closure of what the roots
        depend on — the self-contained fragment needed to evaluate them.
        """
        visited: Set[str] = set()
        queue: List[str] = sorted(root_ids)
        while queue:
            nid = queue.pop(0)
            if nid in visited:
                continue
            visited.add(nid)
            for dep in self.dependencies(nid):
                if dep not in visited:
                    queue.append(dep)
        sub = ClaimGraph()
        for nid in sorted(visited):
            if nid in self._nodes:
                sub.add_node(self._nodes[nid])
        for nid in sorted(visited):
            for dep in self.dependencies(nid):
                if dep in visited:
                    sub.add_dependency(nid, dep)
        return sub


